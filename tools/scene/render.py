def _sdf_colonnade(w, px, py, pz):
    # a receding row of slender slabs: architecture-studio concept
    d = np.full(px.size, 1e9, F)
    for i in range(7):
        z = 30 + i * 9.0
        d = np.minimum(d, sd_box(px, py, pz, (6.0 + i * 0.4, 8.0, z), (0.9, 8.0, 2.6)) - 0.05)
    return d


def _sdf_rings(w, px, py, pz):
    # a floating sphere wrapped in a thin ring: audio-product concept
    c = (3.0, 7.0, 40.0)
    s = sd_sphere(px, py, pz, c, 4.2)
    # ring tilted around z
    a = math.radians(18)
    qx = (px - c[0]) * math.cos(a) + (py - c[1]) * math.sin(a)
    qy = -(px - c[0]) * math.sin(a) + (py - c[1]) * math.cos(a)
    qz = pz - c[2]
    ring = np.sqrt((np.sqrt(qx * qx + qz * qz) - 7.2) ** 2 + qy * qy) - 0.12
    return np.minimum(s, ring)


def _sdf_grid(w, px, py, pz):
    # a field of plinths of varying height: data / web-app concept
    cell = 4.0
    gx = np.floor((px + 20) / cell)
    gz = np.floor((pz - 20) / cell)
    inside = (gx >= 0) & (gx < 10) & (gz >= 0) & (gz < 10)
    hgt = 0.6 + 6.5 * _hash2(gx.astype(np.int64), gz.astype(np.int64), 3) ** 2.5
    cx = (gx + 0.5) * cell - 20
    cz = (gz + 0.5) * cell + 20
    box = sd_box(px, py, pz, (cx, hgt / 2, cz), (1.3, hgt / 2, 1.3)) - 0.03
    # never step past the current cell's walls: neighbours may be taller
    wall = np.minimum(cell / 2 - np.abs(px - cx), cell / 2 - np.abs(pz - cz)) + 0.12  # > hit epsilon at range
    outside = sd_box(px, py, pz, (0, 3.6, 40), (20, 3.6, 20))
    return np.where(inside, np.minimum(box, wall), np.maximum(outside, 0.15))  # > hit epsilon at range


def _sdf_gate(w, px, py, pz):
    # pointed arch gateway (iwan-inspired): hospitality brand concept
    c = (2.0, 0.0, 44.0)
    qx = np.abs(px - c[0])
    qy = py - c[1]
    outer = sd_box(px, py, pz, (c[0], 9.0, c[2]), (7.0, 9.0, 1.6))
    # opening: rectangle + pointed top (intersection of two circles)
    rect = np.maximum(qx - 3.0, np.maximum(-qy, qy - 9.0))
    r = 6.0
    circ = np.sqrt((qx + (r - 3.0)) ** 2 + (qy - 9.0) ** 2) - r
    arch = np.maximum(circ, 6.0 - qy)  # overlaps the rectangle: no internal seam
    opening2d = np.minimum(rect, np.maximum(arch, -qy))
    opening = extrude(opening2d, pz, c[2], 3.0)
    return np.maximum(outer, -opening)


