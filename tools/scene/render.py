def tonemap(c, exposure):
    x = c * exposure
    x = (x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14)
    x = np.clip(x, 0, 1)
    # gentle split-tone: cool shadows, warm highlights
    lum = (x[..., 0] * 0.2126 + x[..., 1] * 0.7152 + x[..., 2] * 0.0722)[..., None]
    x = x + (np.array([-0.004, 0.0, 0.012], F) * (1 - lum) + np.array([0.012, 0.004, -0.010], F) * lum) * 0.8
    x = np.clip(x, 0, 1) ** (1 / 2.2)
    return x


def vignette(img, strength=0.28):
    H, W = img.shape[:2]
    y = (np.arange(H, dtype=F) / H - 0.5)[:, None]
    x = (np.arange(W, dtype=F) / W - 0.5)[None, :]
    v = 1 - strength * np.clip((x * x * 1.1 + y * y * 1.6) * 2.2, 0, 1) ** 1.5
    return img * v[..., None]


def downsample(a, ss):
    if ss == 1:
        return a
    H, W = a.shape[0] // ss, a.shape[1] // ss
    return a[:H * ss, :W * ss].reshape(H, ss, W, ss, *a.shape[2:]).mean(axis=(1, 3))


def save_rgb(a, path):
    Image.fromarray((np.clip(a, 0, 1) * 255 + 0.5).astype(np.uint8), "RGB").save(path, optimize=True)


def _layer(top, mask, ss):
    """Un-premultiplied RGBA layer from a supersampled image and its 0/1 mask."""
    alpha = downsample(mask, ss)
    prem = downsample(top * mask[..., None], ss)
    rgb = np.where(alpha[..., None] > 1e-4, prem / np.maximum(alpha[..., None], 1e-4), 0)
    return np.clip(rgb, 0, 1), alpha


def save_rgba(rgb, alpha, path):
    rgba = np.concatenate([rgb, alpha[..., None]], -1)
    Image.fromarray((rgba * 255 + 0.5).astype(np.uint8), "RGBA").save(path, optimize=True)


def finish(p: Preset, full, back, sky, mask, ss, suffix=""):
    """Layered presets write, far to near:
         -sky     sea, sky, mountains (no planet, no monolith)
         -planet  the planet and its reflection (RGBA)
         -back    sky + planet flattened (fallback / placeholder source)
         -front   monolith, plinth and their reflections (RGBA)
       Composited they reproduce <name>.png exactly."""
    OUT.mkdir(parents=True, exist_ok=True)
    L = p.look
    if p.layered:
        tf = vignette(tonemap(full, L.exposure))
        tb = vignette(tonemap(back, L.exposure))
        ts = vignette(tonemap(sky, L.exposure))
        planet_mask = (np.abs(tb - ts).sum(-1) > 2e-3).astype(F)
        sky_d = downsample(ts, ss)
        planet_rgb, planet_a = _layer(tb, planet_mask, ss)
        front_rgb, front_a = _layer(tf, mask, ss)
        back_d = planet_rgb * planet_a[..., None] + sky_d * (1 - planet_a[..., None])
        comp = front_rgb * front_a[..., None] + back_d * (1 - front_a[..., None])
        save_rgb(comp, OUT / f"{p.name}{suffix}.png")
        save_rgb(back_d, OUT / f"{p.name}{suffix}-back.png")
        save_rgb(sky_d, OUT / f"{p.name}{suffix}-sky.png")
        save_rgba(planet_rgb, planet_a, OUT / f"{p.name}{suffix}-planet.png")
        save_rgba(front_rgb, front_a, OUT / f"{p.name}{suffix}-front.png")
    else:
        save_rgb(downsample(vignette(tonemap(full, L.exposure)), ss), OUT / f"{p.name}{suffix}.png")


