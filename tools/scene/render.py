class Sky:
    def __init__(self, p: Preset):
        L = p.look
        self.L = L
        self.sun = unit(*L.sun_dir)
        self.sun_az = math.atan2(self.sun[0], self.sun[2])
        self.sun_el = math.asin(self.sun[1])
        self.planet = p.planet
        self.show_planet = True  # switched off for the planet-free sky layer
        if p.planet:
            self.pdir = unit(*p.planet.dir)
            self.prad = math.radians(p.planet.radius_deg)

    def gradient(self, d):
        """Sky colour without clouds or sun disc (also used for ambient/fog)."""
        L = self.L
        e = np.clip(d[1], -0.2, 1.0)
        az = np.arctan2(d[0], d[2])
        toward_sun = 0.5 + 0.5 * np.cos(az - self.sun_az)
        horizon = mix(col3(L.horizon_cool), col3(L.horizon), toward_sun ** 1.6)
        t1 = np.exp(-np.maximum(e, 0) * 13.0)
        t2 = smoothstep(0.05, 0.7, e)
        c = mix(col3(L.upper), horizon, t1)
        c = mix(c, col3(L.zenith), t2)
        return c

    def sun_glow(self, d, disc=True):
        L = self.L
        cs = np.maximum(dot(d, self.sun), 0)
        g = 0.10 * cs ** 4 + 0.45 * cs ** 32 + 1.6 * cs ** 420
        if disc:
            g = g + 60.0 * smoothstep(0.99985, 0.99993, cs)
        return col3(L.sun_color) * (g * L.sun_intensity * 0.55)

    def clouds(self, d, base):
        L = self.L
        e = d[1]
        az = np.arctan2(d[0], d[2])
        c = base
        # low cumulus bank resting on the horizon
        band = (e > -0.01) & (e < 0.16)
        if band.any():
            ee = e[band]
            aa = az[band]
            x, y = aa * 7.5, ee * 42.0
            n1 = fbm(x, y * 0.9, 6, L.cloud_seed)
            cover = L.cloud_cover + 0.06 * np.sin(aa * 3.1 + 1.0)
            dens = smoothstep(0.0, 0.16, n1 - (1.0 - cover) - ee * 5.5)
            # light: march a step toward the sun in angle-space
            sx, sy = self.sun_az - aa, self.sun_el - ee
            sl = np.sqrt(sx * sx + sy * sy) + 1e-4
            ox, oy = sx / sl * 0.035, sy / sl * 0.035
            n2 = fbm((aa + ox) * 7.5, (ee + oy) * 42.0 * 0.9, 5, L.cloud_seed)
            occl = smoothstep(0.0, 0.25, n2 - (1.0 - cover) - (ee + oy) * 5.5)
            lit = np.exp(-2.2 * occl)
            near_sun = np.maximum(np.cos(aa - self.sun_az), 0) ** 6
            hz = c[:, band]
            shadow_col = mix(hz, col3(L.horizon_cool) * 0.55, 0.55)
            lit_col = col3(L.horizon) * (1.15 + 1.6 * near_sun) + col3(L.sun_color) * 0.25 * near_sun
            cc = mix(shadow_col, lit_col, lit * (0.35 + 0.65 * smoothstep(0.0, 0.08, ee)))
            # haze the bottom of the bank into the horizon
            cc = mix(cc, hz, smoothstep(0.012, -0.004, ee))
            c[:, band] = mix(hz, cc, dens)
        # high, thin streaks
        hi = e > 0.03
        if hi.any():
            dh = d[0][hi] / e[hi], d[2][hi] / e[hi]
            n3 = fbm(dh[0] * 0.55 + 4.0, dh[1] * 2.4, 5, L.cloud_seed + 40)
            streak = smoothstep(0.62, 0.88, n3) * smoothstep(0.03, 0.10, e[hi]) * (1 - smoothstep(0.22, 0.5, e[hi]))
            warm = mix(col3(L.horizon_cool) * 0.45, col3(L.horizon) * 0.55, np.maximum(np.cos(az[hi] - self.sun_az), 0) ** 2)
            c[:, hi] = mix(c[:, hi], warm, streak * 0.22)
        return c

    def mountains(self, d, c):
        e = d[1]
        sel = (e > -0.002) & (e < 0.05)
        if not sel.any():
            return c
        az = np.arctan2(d[0][sel], d[2][sel])
        ridge = 0.004 + 0.030 * fbm(az * 9.0 + 20.0, np.zeros_like(az) + 3.3, 6, 91) ** 2.2
        ridge *= smoothstep(-0.9, -0.2, az) + smoothstep(0.55, 0.95, az)  # two ranges, clear behind the portal
        far = 0.012 + 0.012 * fbm(az * 5.0 + 3.0, np.zeros_like(az) + 8.1, 4, 7) ** 1.5
        ee = e[sel]
        base = c[:, sel]
        hazecol = mix(base, col3(self.L.horizon_cool) * 0.9, 0.35)
        m_far = (ee < far)
        out = np.where(m_far, mix(base, hazecol * 1.02, 0.55), base)
        m_near = (ee < ridge)
        litside = np.maximum(np.cos(az - self.sun_az), 0) ** 4
        nearcol = mix(col3(self.L.horizon_cool) * 0.38, col3(self.L.horizon) * 0.8, litside * 0.7)
        out = np.where(m_near, mix(base, nearcol, 0.8), out)
        c[:, sel] = out
        return c

    def planet_hit(self, d):
        """Returns (mask, colour) for rays hitting the planet disc."""
        P = self.planet
        if not P or not self.show_planet:
            return None, None
        cs = dot(d, self.pdir)
        cr = math.cos(self.prad)
        m = cs > cr
        if not m.any():
            return m, None
        dd = (d[0][m], d[1][m], d[2][m])
        # local sphere normal from angular offset
        ang = np.arccos(np.clip(cs[m], -1, 1)) / self.prad  # 0..1 from centre
        up = np.array([0, 1, 0], F)
        right = np.cross(up, self.pdir)
        right /= np.linalg.norm(right)
        upv = np.cross(self.pdir, right)
        ox = dot(dd, right)
        oy = dot(dd, upv)
        l = np.sqrt(ox * ox + oy * oy) + 1e-9
        u = ox / l * ang
        v = oy / l * ang
        w = np.sqrt(np.clip(1 - u * u - v * v, 0, 1))
        # normal in world space (facing camera = -pdir)
        n = (u * right[0] + v * upv[0] - w * self.pdir[0],
             u * right[1] + v * upv[1] - w * self.pdir[1],
             u * right[2] + v * upv[2] - w * self.pdir[2])
        diff = np.clip(dot(n, self.sun), 0, 1)
        tex = 0.80 + 0.22 * fbm(u * 2.2 + 5, v * 2.2 + 2, 6, 55) - 0.08 * smoothstep(0.5, 0.8, fbm(u * 4 + 1, v * 4, 4, 21))
        amb = mix(col3(self.L.upper) * 3.0, col3(self.L.horizon) * 0.7, 0.5 + 0.5 * (-v))
        c = col3((0.96, 0.92, 0.86)) * P.albedo * tex * (col3(self.L.sun_color) * diff ** 0.8 * 2.6 + amb * 0.32)
        edge = smoothstep(1.0, 0.985, ang)
        return m, (c, edge)

    def background(self, d):
        c = self.gradient(d)
        c = self.clouds(d, c)
        c = self.mountains(d, c)
        m, pc = self.planet_hit(d)
        if pc is not None:
            pcol, edge = pc
            base = c[:, m]
            pcol = mix(pcol, base, self.planet.haze)
            c[:, m] = mix(base, pcol, edge)
        c = c + self.sun_glow(d)
        return c


