class Renderer:
    def __init__(self, p: Preset):
        self.p = p
        self.world = World(p)
        self.sky = Sky(p)

    def fog(self, c, t, d):
        L = self.p.look
        f = 1.0 - np.exp(-t * L.haze)
        fc = self.sky.gradient((d[0], np.maximum(d[1], 0) * 0.3, d[2])) + self.sky.sun_glow(d, disc=False) * 0.25
        return mix(c, fc, f)

    def shade_object(self, o, d, t, mid, with_struct):
        w, sky, L = self.world, self.sky, self.p.look
        p = (o[0] + d[0] * t, o[1] + d[1] * t, o[2] + d[2] * t)
        n = w.normal(*p, with_struct)
        sun = sky.sun
        ndl = np.clip(dot(n, sun), 0, 1)
        ndl_sel = ndl > 0
        sh = np.ones_like(ndl)
        if ndl_sel.any():
            idx = np.nonzero(ndl_sel)[0]
            pp = (p[0][idx] + n[0][idx] * 0.03, p[1][idx] + n[1][idx] * 0.03, p[2][idx] + n[2][idx] * 0.03)
            sh[idx] = w.soft_shadow(pp, sun, with_struct)
        occ = w.ao(p, n, with_struct)
        # albedo by material
        alb = np.zeros((3, t.size), F)
        rough_spec = np.zeros(t.size, F)
        is_m = (mid == ID_MONO) | (mid == ID_PROP)
        is_pl = mid == ID_PLINTH
        is_j = mid == ID_JETTY
        is_f = mid == ID_FIGURE
        if is_m.any() or is_pl.any():
            s = is_m | is_pl
            gx = p[0][s] + p[2][s] * 0.7
            gy = p[1][s]
            grain = 0.86 + 0.22 * fbm(gx * 0.35, gy * 0.12, 5, 5) + 0.06 * fbm(gx * 4.0, gy * 4.0, 3, 9)
            # formwork joints every 2.4 units give the monolith its scale
            joint = 1.0 - 0.10 * smoothstep(0.06, 0.0, np.abs((gy / 2.4) % 1.0 - 0.5) - 0.47)
            base = col3((0.25, 0.243, 0.235))
            alb[:, s] = base * (grain * joint)
            alb[:, is_pl] *= 0.6
            rough_spec[s] = 0.22
        if is_j.any():
            alb[:, is_j] = col3((0.045, 0.047, 0.05))
            rough_spec[is_j] = 0.35
        if is_f.any():
            alb[:, is_f] = col3((0.02, 0.019, 0.019))
            rough_spec[is_f] = 0.08
        # lighting: sun + sky hemisphere + warm water bounce
        sky_amb = sky.gradient((n[0], np.maximum(n[1], 0.05), n[2]))
        bounce = col3(L.horizon) * 0.18 * np.clip(-n[1] * 0.5 + 0.35, 0, 1)
        sunlight = col3(L.sun_color) * (L.sun_intensity * ndl * sh)
        diffuse = alb * (sunlight + (sky_amb * 0.7 + bounce) * occ)
        # polished stone reflection
        vd = dot(d, n)
        r = (d[0] - 2 * vd * n[0], d[1] - 2 * vd * n[1], d[2] - 2 * vd * n[2])
        fres = 0.04 + 0.96 * (1 - np.clip(-vd, 0, 1)) ** 5
        env = sky.gradient((r[0], np.abs(r[1]), r[2])) + sky.sun_glow(r, disc=False) * 0.6 * sh
        c = diffuse + env * (fres * rough_spec * 2.0)
        return self.fog(c, t, d)

    def trace(self, o, d, with_struct=True, depth=0):
        w = self.world
        n = o[0].size
        c = np.zeros((3, n), F)
        involved = np.zeros(n, bool)
        tw = np.where(d[1] < -1e-5, -o[1] / np.minimum(d[1], -1e-5), np.inf).astype(F)
        t0, t1 = w.aabb(o, d)
        t1 = np.minimum(t1, tw)
        t, hit, mid = w.march(o, d, t0, t1, with_struct, steps=self.p.steps)
        if hit.any():
            i = np.nonzero(hit)[0]
            c[:, i] = self.shade_object(tuple(a[i] for a in o), tuple(a[i] for a in d), t[i], mid[i], with_struct)
            involved[i] = np.isin(mid[i], STRUCT_IDS)
        water = (~hit) & np.isfinite(tw) & (depth == 0)
        if water.any():
            i = np.nonzero(water)[0]
            cw, inv = self.shade_water(tuple(a[i] for a in o), tuple(a[i] for a in d), tw[i], with_struct)
            c[:, i] = cw
            involved[i] = inv
        skym = (~hit) & ~water
        if skym.any():
            i = np.nonzero(skym)[0]
            c[:, i] = self.sky.background(tuple(a[i] for a in d))
        return c, involved

    def shade_water(self, o, d, t, with_struct):
        L = self.p.look
        p = (o[0] + d[0] * t, o[1] * 0, o[2] + d[2] * t)
        # ripples: anisotropic height field, faded with distance to avoid aliasing
        s = 0.0065 * L.ripple / (1.0 + t * 0.02)
        x, z = p[0], p[2]
        e = 0.05
        h0 = fbm(x * 0.35, z * 1.4, 4, 77)
        hx = fbm((x + e) * 0.35, z * 1.4, 4, 77)
        hz = fbm(x * 0.35, (z + e) * 1.4, 4, 77)
        n = norm((-(hx - h0) / e * s * 6, np.ones_like(x), -(hz - h0) / e * s * 6))
        vd = dot(d, n)
        r = (d[0] - 2 * vd * n[0], np.maximum(d[1] - 2 * vd * n[1], 0.0015), d[2] - 2 * vd * n[2])
        r = norm(r)
        o2 = (p[0] + r[0] * 0.01, p[1] + 0.01, p[2] + r[2] * 0.01)
        refl, inv = self.trace(o2, r, with_struct, depth=1)
        fres = 0.02 + 0.98 * (1 - np.clip(-vd, 0, 1)) ** 5
        k = np.clip(fres * 1.1 + 0.28, 0, 0.90) * L.reflect
        c = mix(col3(L.water), refl * 0.88, k)
        return self.fog(c, t, d), inv

    # -- image ---------------------------------------------------------------
    def rays(self, rows, W, H):
        cam = self.p.cam
        yaw, pitch = math.radians(cam.yaw), math.radians(cam.pitch)
        f = np.array([math.sin(yaw) * math.cos(pitch), math.sin(pitch), math.cos(yaw) * math.cos(pitch)], F)
        r = np.cross(np.array([0, 1, 0], F), f)
        r /= np.linalg.norm(r)
        u = np.cross(f, r)
        th = math.tan(math.radians(cam.vfov) / 2)
        asp = W / H
        xs = ((np.arange(W, dtype=F) + 0.5) / W * 2 - 1) * th * asp
        ys = (1 - (rows.astype(F) + 0.5) / H * 2) * th
        X, Y = np.meshgrid(xs, ys)
        X, Y = X.ravel(), Y.ravel()
        d = (f[0] + X * r[0] + Y * u[0], f[1] + X * r[1] + Y * u[1], f[2] + X * r[2] + Y * u[2])
        d = norm(d)
        o = tuple(np.full_like(X, v) for v in cam.pos)
        return o, d

    def render(self, ss=2, scale=1.0, chunk_rows=96):
        cam = self.p.cam
        W, H = int(cam.width * scale) * ss, int(cam.height * scale) * ss
        full = np.zeros((H, W, 3), F)
        back = np.zeros((H, W, 3), F) if self.p.layered else None
        sky = np.zeros((H, W, 3), F) if self.p.layered else None
        mask = np.zeros((H, W), F)
        t_start = time.time()
        for y0 in range(0, H, chunk_rows):
            rows = np.arange(y0, min(H, y0 + chunk_rows))
            o, d = self.rays(rows, W, H)
            c, inv = self.trace(o, d, True)
            full[rows[0]:rows[-1] + 1] = c.T.reshape(len(rows), W, 3)
            if self.p.layered:
                cb = c.copy()
                if inv.any():
                    i = np.nonzero(inv)[0]
                    cb[:, i], _ = self.trace(tuple(a[i] for a in o), tuple(a[i] for a in d), False)
                back[rows[0]:rows[-1] + 1] = cb.T.reshape(len(rows), W, 3)
                mask[rows[0]:rows[-1] + 1] = inv.reshape(len(rows), W)
                # third pass: no monolith and no planet -> the far sky/sea layer
                self.sky.show_planet = False
                cs, _ = self.trace(o, d, False)
                self.sky.show_planet = True
                # below the horizon keep the planet's reflection: it belongs to the sea
                below = d[1] <= 0
                cs[:, below] = cb[:, below]
                sky[rows[0]:rows[-1] + 1] = cs.T.reshape(len(rows), W, 3)
            done = (y0 + chunk_rows) / H
            el = time.time() - t_start
            print(f"\r  {self.p.name}: {min(done, 1) * 100:5.1f}%  {el:6.1f}s", end="", flush=True)
        print()
        return full, back, sky, mask


