# --------------------------------------------------------------------------
# small vector helpers (vectors are tuples of 1-D float32 arrays)
# --------------------------------------------------------------------------

def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def norm(v):
    inv = 1.0 / np.sqrt(np.maximum(dot(v, v), 1e-20))
    return (v[0] * inv, v[1] * inv, v[2] * inv)


def unit(x, y, z):
    l = math.sqrt(x * x + y * y + z * z)
    return np.array([x / l, y / l, z / l], dtype=F)


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def mix(a, b, t):
    return a + (b - a) * t


def col3(rgb, n=None):
    """Broadcastable colour column (3, 1)."""
    return np.asarray(rgb, dtype=F).reshape(3, 1)


# --------------------------------------------------------------------------
# noise
# --------------------------------------------------------------------------

def _hash2(ix, iy, seed):
    h = (ix * 374761393 + iy * 668265263 + seed * 1442695041) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    h = h ^ (h >> 16)
    return (h & 0xFFFFFF).astype(F) * F(1.0 / 0xFFFFFF)


def vnoise(x, y, seed=0):
    xf = np.floor(x)
    yf = np.floor(y)
    ix = xf.astype(np.int64)
    iy = yf.astype(np.int64)
    fx = (x - xf).astype(F)
    fy = (y - yf).astype(F)
    ux = fx * fx * (3 - 2 * fx)
    uy = fy * fy * (3 - 2 * fy)
    a = _hash2(ix, iy, seed)
    b = _hash2(ix + 1, iy, seed)
    c = _hash2(ix, iy + 1, seed)
    d = _hash2(ix + 1, iy + 1, seed)
    return a + (b - a) * ux + (c - a) * uy + (a - b - c + d) * ux * uy


def fbm(x, y, octaves=5, seed=0, gain=0.5):
    s = np.zeros_like(x, dtype=F)
    amp, total = 0.5, 0.0
    c, sn = math.cos(0.6), math.sin(0.6)
    for i in range(octaves):
        s += amp * vnoise(x, y, seed + i * 17)
        total += amp
        x, y = (c * x - sn * y) * 2.03 + 1.7, (sn * x + c * y) * 2.03 + 9.2
        amp *= gain
    return s / total


