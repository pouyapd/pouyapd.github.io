"""
P. DESIGN — procedural scene renderer.

Renders the original hero environment ("the portal P": a monumental P-shaped
monolith standing in a mirror sea at golden hour) and the concept-project
covers with a small vectorised signed-distance-field ray-marcher.

Everything in the images is generated by this script, so the studio owns the
artwork outright. Re-render with:

    python tools/scene/render.py hero-desktop            # full quality
    python tools/scene/render.py hero-desktop --preview  # quick low-res check

Outputs go to tools/scene/out/ as PNG. `npm run assets` then converts them to
AVIF/WebP in public/media/.

Layers: hero presets also write `<name>-back.png` (scene without the monolith)
and `<name>-front.png` (monolith + its reflection, RGBA). The site composites
them for real parallax depth; composited they reproduce `<name>.png` exactly.
"""

